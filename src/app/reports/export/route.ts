import { headers } from "next/headers";
import { getActiveSession } from "@/lib/auth-guards";
import { db } from "@/lib/db";
import { formatDateIST, toISODateStringIST } from "@/lib/dates";
import { amountReceived, balanceDue, bookingTotal } from "@/lib/calc";
import { parseMonth } from "@/features/metrics/filters";
import {
  getCitySummary,
  getConversionBySource,
  getMonthlyPLData,
} from "@/features/metrics/queries";
import { toCSVRow } from "@/features/reports/csv";

export async function GET(request: Request) {
  // STRICT ROUTE HANDLER GUARD: 401 when logged out, 403 when no permission; NEVER redirect
  const session = await getActiveSession(await headers());
  if (!session) {
    return new Response("Unauthorized", { status: 401 });
  }

  if (session.user.role !== "PARTNER") {
    return new Response("Forbidden: Partners only", { status: 403 });
  }

  const url = new URL(request.url);
  const rawMonth = url.searchParams.get("month");
  const month = parseMonth(rawMonth);

  const [plData, conversionData, cityData, allBookings] = await Promise.all([
    getMonthlyPLData(month),
    getConversionBySource(),
    getCitySummary(),
    db.booking.findMany({
      select: {
        code: true,
        clientName: true,
        phone: true,
        city: true,
        venue: true,
        eventDate: true,
        packageName: true,
        basePrice: true,
        travelCharge: true,
        discount: true,
        status: true,
        unit: true,
        payments: {
          select: {
            amount: true,
            kind: true,
            voidedAt: true,
          },
        },
      },
      orderBy: { eventDate: "asc" },
    }),
  ]);

  // Filter bookings for this IST event month
  const monthBookings = allBookings.filter((b) =>
    toISODateStringIST(new Date(b.eventDate)).startsWith(month)
  );

  const lines: string[] = [];

  // Metadata
  lines.push(toCSVRow(["Junabooth CRM - Monthly Business & Performance Report"]));
  lines.push(toCSVRow(["Month", month]));
  lines.push(toCSVRow(["Generated At (IST)", formatDateIST(new Date())]));
  lines.push(toCSVRow(["Generated By", session.user.name]));
  lines.push("");

  // SECTION 1: Monthly Profit & Loss
  const { current, previous, comparison } = plData;
  lines.push(toCSVRow(["SECTION 1: MONTHLY PROFIT & LOSS STATEMENT"]));
  lines.push(toCSVRow(["Financial Line Item", `Current Month (${month})`, `Previous Month (${previous.month})`, "Change"]));
  lines.push(toCSVRow(["Gross Revenue (INR)", current.revenue, previous.revenue, comparison.revenueDiff]));
  lines.push(toCSVRow(["Direct Event Costs (INR)", current.directCosts, previous.directCosts, comparison.directCostsDiff]));
  lines.push(toCSVRow(["Gross Profit (INR)", current.grossProfit, previous.grossProfit, comparison.grossProfitDiff]));
  lines.push(toCSVRow(["Gross Margin (%)", current.grossMargin ?? "N/A", previous.grossMargin ?? "N/A", ""]));
  lines.push(toCSVRow(["Overheads - Setup (INR)", current.overheads.setup, previous.overheads.setup, ""]));
  lines.push(toCSVRow(["Overheads - Marketing (INR)", current.overheads.marketing, previous.overheads.marketing, ""]));
  lines.push(toCSVRow(["Overheads - General & Admin (INR)", current.overheads.general, previous.overheads.general, ""]));
  lines.push(toCSVRow(["Total Overheads (INR)", current.overheads.total, previous.overheads.total, comparison.overheadsDiff]));
  lines.push(toCSVRow(["Net Profit (INR)", current.netProfit, previous.netProfit, comparison.netProfitDiff]));
  lines.push(toCSVRow(["Net Margin (%)", current.netMargin ?? "N/A", previous.netMargin ?? "N/A", ""]));
  lines.push(toCSVRow(["Active Event Count", current.bookingCount, previous.bookingCount, ""]));
  lines.push(toCSVRow(["Cancelled Slots", current.cancelledCount, previous.cancelledCount, ""]));
  lines.push("");

  // SECTION 2: Conversion by Source
  lines.push(toCSVRow(["SECTION 2: LEAD CONVERSION BY SOURCE"]));
  lines.push(toCSVRow(["Source", "Total Leads", "Won", "Lost", "Open", "Conversion Rate (%)"]));
  for (const row of conversionData) {
    lines.push(
      toCSVRow([
        row.source,
        row.totalLeads,
        row.won,
        row.lost,
        row.open,
        row.conversion !== null ? `${row.conversion}%` : "N/A",
      ])
    );
  }
  lines.push("");

  // SECTION 3: City Performance
  lines.push(toCSVRow(["SECTION 3: REGIONAL CITY PERFORMANCE"]));
  lines.push(toCSVRow(["City", "Events", "Billed (INR)", "Average Deal Size (INR)", "Gross Margin (%)"]));
  for (const c of cityData) {
    lines.push(
      toCSVRow([
        c.city,
        c.events,
        c.billed,
        c.avgDealSize,
        c.grossMargin !== null ? `${c.grossMargin}%` : "N/A",
      ])
    );
  }
  lines.push("");

  // SECTION 4: Bookings in this month
  lines.push(toCSVRow([`SECTION 4: BOOKINGS SCHEDULED FOR ${month}`]));
  lines.push(
    toCSVRow([
      "Booking Code",
      "Client Name",
      "Phone",
      "City",
      "Venue",
      "Event Date",
      "Package",
      "Unit",
      "Status",
      "Total Amount (INR)",
      "Received (INR)",
      "Balance (INR)",
    ])
  );

  for (const b of monthBookings) {
    const total = bookingTotal(b);
    const received = amountReceived(b.payments);
    const balance = balanceDue(b, b.payments);

    lines.push(
      toCSVRow([
        b.code,
        b.clientName,
        b.phone,
        b.city ?? "N/A",
        b.venue ?? "N/A",
        formatDateIST(b.eventDate),
        b.packageName,
        b.unit ?? "Unassigned",
        b.status,
        total,
        received,
        balance,
      ])
    );
  }

  // Prepend UTF-8 BOM for Excel compatibility (0xEF, 0xBB, 0xBF)
  const encoder = new TextEncoder();
  const csvBuffer = encoder.encode("\uFEFF" + lines.join("\r\n"));

  return new Response(csvBuffer, {
    status: 200,
    headers: {
      "Content-Type": "text/csv; charset=utf-8",
      "Content-Disposition": `attachment; filename="junabooth-report-${month}.csv"`,
      "Cache-Control": "no-store, no-cache, must-revalidate",
    },
  });
}
